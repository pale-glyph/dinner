using Dinner.MealPlanningService.Application;
using Dinner.MealPlanningService.Application.Ports;
using Dinner.MealPlanningService.Infrastructure;
using Dinner.MealPlanningService.Web;
using Dinner.ServiceDefaults;
using Npgsql;

var builder = WebApplication.CreateBuilder(args).AddDinnerServiceDefaults();
builder.Services.AddCors(options => options.AddDefaultPolicy(policy => policy.AllowAnyOrigin().AllowAnyHeader().AllowAnyMethod()));
var connectionString = builder.Configuration.GetConnectionString("Dinner") ?? "Host=localhost;Port=5432;Database=dinner;Username=dinner;Password=change-me";
builder.Services.AddSingleton(_ => NpgsqlDataSource.Create(connectionString));
builder.Services.AddSingleton<PostgresMealPlanRepository>();
builder.Services.AddSingleton<IMealPlanRepository>(provider => provider.GetRequiredService<PostgresMealPlanRepository>());
builder.Services.AddSingleton<IMealPlanDatabaseInitializer>(provider => provider.GetRequiredService<PostgresMealPlanRepository>());
builder.Services.AddSingleton<IClock, SystemClock>();
builder.Services.AddScoped<MealPlanService>();
var app = builder.Build().MapDinnerServiceDefaults("meal-planning-service");
app.UseCors();
await app.Services.GetRequiredService<IMealPlanDatabaseInitializer>().InitializeAsync(CancellationToken.None);
app.MapMealPlanEndpoints();
app.Run();
